import { hexToKmlColor } from './colors.js';

const esc = (s) =>
  String(s).replace(/[<>&'"]/g, (c) => ({ '<': '&lt;', '>': '&gt;', '&': '&amp;', "'": '&apos;', '"': '&quot;' })[c]);

/**
 * altitudeMode (what the numbers mean):
 *   'ellipsoid'        WGS84 ellipsoid height = home.h0 + metres above takeoff.
 *                      Written as KML `absolute`. Google Earth reads `absolute` as
 *                      MSL, so its preview floats ~geoid-undulation (about 30 m
 *                      lower in Indiana) off from where the drone will fly.
 *   'relativeToGround' metres above the takeoff point (exact when the takeoff
 *                      ground matches the ground under the path).
 *   'absolute'         home.msl + metres above takeoff (MSL).
 */
export function buildKml(project, { altitudeMode = 'ellipsoid', segments = false } = {}) {
  const { home, camera, waypoints: wps, name } = project;
  if (!home) throw new Error('Set a home/takeoff point first.');
  if (altitudeMode === 'absolute' && !Number.isFinite(home.msl)) {
    throw new Error('Absolute altitude needs the takeoff elevation (MSL).');
  }
  const base = { absolute: home.msl, ellipsoid: home.h0, relativeToGround: 0 }[altitudeMode];
  if (base === undefined) throw new Error(`Unknown altitude mode ${altitudeMode}`);
  const kmlMode = altitudeMode === 'relativeToGround' ? 'relativeToGround' : 'absolute';
  const alt = (a) => (base + a).toFixed(2);
  const coord = (p, a) => `${p.lon.toFixed(8)},${p.lat.toFixed(8)},${alt(a)}`;
  const mode = `<altitudeMode>${kmlMode}</altitudeMode>`;

  const points = wps
    .map(
      (w, i) => `    <Placemark>
      <name>WP${i + 1}</name>
      <Style><IconStyle><color>${hexToKmlColor(w.color)}</color><scale>0.7</scale></IconStyle></Style>
      <ExtendedData>
        <Data name="index"><value>${i + 1}</value></Data>
        <Data name="color"><value>${esc(w.color)}</value></Data>
        <Data name="sync"><value>${w.sync ? 1 : 0}</value></Data>
        <Data name="alt_above_takeoff_m"><value>${w.alt.toFixed(2)}</value></Data>
      </ExtendedData>
      <Point>${mode}<coordinates>${coord(w, w.alt)}</coordinates></Point>
    </Placemark>`,
    )
    .join('\n');

  const segmentPlacemarks = segments
    ? wps
    .slice(0, -1)
    .map(
      (w, i) => `    <Placemark>
      <name>Seg ${i + 1}</name>
      <Style><LineStyle><color>${hexToKmlColor(w.color)}</color><width>4</width></LineStyle></Style>
      <LineString>${mode}<coordinates>${coord(w, w.alt)} ${coord(wps[i + 1], wps[i + 1].alt)}</coordinates></LineString>
    </Placemark>`,
    )
    .join('\n')
    : '';

  const marker = (label, p, a, extra = '') => `    <Placemark>
      <name>${esc(label)}</name>${extra}
      <Point>${mode}<coordinates>${coord(p, a)}</coordinates></Point>
    </Placemark>`;

  return `<?xml version="1.0" encoding="UTF-8"?>
<kml xmlns="http://www.opengis.net/kml/2.2">
  <Document>
    <name>${esc(name || 'Light painting')}</name>
    <description>Generated by drone-lightpaint. Altitudes are metres ${
      { absolute: 'MSL', ellipsoid: 'above the WGS84 ellipsoid', relativeToGround: 'above the takeoff point' }[altitudeMode]
    }.</description>
  <Folder>
    <name>Reference</name>
${marker('Home / takeoff', home, 0)}${camera ? '\n' + marker('Camera', camera, 1.5) : ''}
  </Folder>
  <Folder>
    <name>Waypoints</name>
${points}
  </Folder>
${
    segments
      ? `  <Folder>
    <name>Path</name>
${segmentPlacemarks}
  </Folder>
`
      : ''
  }  </Document>
</kml>
`;
}

/** What the ESP32 will eventually consume: one colour per sync blink. */
export function buildCues(project) {
  return {
    name: project.name,
    cues: project.waypoints.map((w, i) => ({
      i,
      sync: w.sync,
      rgb: [1, 3, 5].map((k) => parseInt(w.color.slice(k, k + 2), 16)),
    })),
  };
}
